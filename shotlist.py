def _sum(pred_key):
    out = []
    for k, _ in Counter(r[pred_key] for r in ROWS).most_common():
        rows_k = [r for r in ROWS if r[pred_key] == k]
        m = sum(r['דק׳'] for r in rows_k)
        out.append([k, len(rows_k), m, round(m / 60.0, 1)])
    return out


